// Bundles content/blog/*.md into a module: Cloudflare Workers have no filesystem to read them from at runtime.
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "content", "blog");
const posts = Object.fromEntries(
  fs.readdirSync(dir).filter((f) => f.endsWith(".md")).sort().map((f) => [path.basename(f, ".md"), fs.readFileSync(path.join(dir, f), "utf8")]),
);
fs.writeFileSync(path.join(process.cwd(), "lib", "blog-posts.generated.ts"), `// Generated by scripts/gen-blog.mjs. Do not edit.\nexport const RAW_POSTS: Record<string, string> = ${JSON.stringify(posts, null, 2)};\n`);
console.log(`bundled ${Object.keys(posts).length} blog posts`);
